CREATE DATABASE IF NOT EXISTS vote_system DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE vote_system;

CREATE TABLE IF NOT EXISTS user (
  id INT PRIMARY KEY AUTO_INCREMENT,
  username VARCHAR(80) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS survey (
  id INT PRIMARY KEY AUTO_INCREMENT,
  public_id VARCHAR(36) NOT NULL UNIQUE,
  title VARCHAR(200) NOT NULL,
  description TEXT,
  deadline DATETIME NULL,
  closed BOOLEAN NOT NULL DEFAULT FALSE,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  user_id INT NOT NULL,
  CONSTRAINT fk_survey_user FOREIGN KEY (user_id) REFERENCES user(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS question (
  id INT PRIMARY KEY AUTO_INCREMENT,
  survey_id INT NOT NULL,
  text TEXT NOT NULL,
  kind VARCHAR(20) NOT NULL,
  required BOOLEAN NOT NULL DEFAULT TRUE,
  position INT NOT NULL DEFAULT 0,
  CONSTRAINT fk_question_survey FOREIGN KEY (survey_id) REFERENCES survey(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS `option` (
  id INT PRIMARY KEY AUTO_INCREMENT,
  question_id INT NOT NULL,
  text VARCHAR(200) NOT NULL,
  position INT NOT NULL DEFAULT 0,
  CONSTRAINT fk_option_question FOREIGN KEY (question_id) REFERENCES question(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS response (
  id INT PRIMARY KEY AUTO_INCREMENT,
  survey_id INT NOT NULL,
  ip_hash VARCHAR(64) NOT NULL,
  visitor_token VARCHAR(64) NOT NULL,
  submitted_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_response_visitor UNIQUE (survey_id, visitor_token),
  CONSTRAINT fk_response_survey FOREIGN KEY (survey_id) REFERENCES survey(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS answer (
  id INT PRIMARY KEY AUTO_INCREMENT,
  response_id INT NOT NULL,
  question_id INT NOT NULL,
  text_value TEXT NULL,
  option_id INT NULL,
  CONSTRAINT fk_answer_response FOREIGN KEY (response_id) REFERENCES response(id) ON DELETE CASCADE,
  CONSTRAINT fk_answer_question FOREIGN KEY (question_id) REFERENCES question(id) ON DELETE CASCADE,
  CONSTRAINT fk_answer_option FOREIGN KEY (option_id) REFERENCES `option`(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
